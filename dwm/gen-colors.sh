#!/usr/bin/env bash
#
# Write colors.h for the dwm build from the current pywal palette.
#
# dwm compiles its palette in, so this runs at build time and a new wallpaper
# means a rebuild. The four source colors and their fallbacks match
# awesome/theme/colors.lua, and the SchemeNorm/SchemeSel mapping matches
# awesome/theme/theme.lua, so both window managers read as the same theme.
#
# Writes to $1, or to colors.h next to this script.

set -euo pipefail

readonly wal_json=$HOME/.cache/wal/colors.json
readonly out=${1:-$(dirname "${BASH_SOURCE[0]}")/colors.h}

# Fallbacks, used when pywal has never run or its output is unreadable.
primary=#dbdbdb
highlight=#1a5598
background=#091a34
secondary=#d3dae3

if [[ -r $wal_json ]] && command -v jq >/dev/null; then
    # One jq pass, tab separated. A malformed colors.json exits non-zero here
    # and the fallbacks stand.
    if read -r bg fg hl < <(jq -r --exit-status \
        '[.special.background, .special.foreground, .colors.color4] | @tsv' \
        "$wal_json" 2>/dev/null); then
        background=$bg
        secondary=$fg
        highlight=$hl
    fi
fi

# awesome derives fg_normal by scaling each channel of the highlight color by
# 1.4 and clamping at 255. Unfocused bar text is that color.
brighten() {
    local hex=${1#\#}
    printf '#%02X%02X%02X' \
        "$(( (0x${hex:0:2} * 14 / 10) > 255 ? 255 : 0x${hex:0:2} * 14 / 10 ))" \
        "$(( (0x${hex:2:2} * 14 / 10) > 255 ? 255 : 0x${hex:2:2} * 14 / 10 ))" \
        "$(( (0x${hex:4:2} * 14 / 10) > 255 ? 255 : 0x${hex:4:2} * 14 / 10 ))"
}

readonly fg_normal=$(brighten "$highlight")

cat > "$out" <<EOF
/* Generated by dwm/gen-colors.sh. Edit that script, not this file. */

static const char col_fg_normal[]  = "$fg_normal";
static const char col_fg_focus[]   = "$primary";
static const char col_bg_normal[]  = "$background";
static const char col_bg_focus[]   = "$highlight";
static const char col_fg_urgent[]  = "$secondary";

static const char *colors[][3] = {
	/*               fg             bg             border       */
	[SchemeNorm] = { col_fg_normal, col_bg_normal, col_bg_normal },
	[SchemeSel]  = { col_fg_focus,  col_bg_focus,  col_bg_focus  },
};
EOF

printf 'colors.h: bg %s  fg %s  focus %s\n' "$background" "$fg_normal" "$highlight"
